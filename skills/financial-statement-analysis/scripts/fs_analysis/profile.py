# 出现这些词说明是备抵、明细或融资类科目，不做包含匹配
CONFLICT_KEYWORDS = [
    "坏账准备", "跌价准备", "减值准备", "累计折旧", "累计摊销", "减值", "融资",
    "账面余额", "原值", "其中", "附注", "明细",
]

SKIP_ROW_PATTERNS = [
    "法定代表人", "主管会计", "会计机构负责人", "制表", "编制人", "单位:", "单位：",
    "行次", "审计报告", "附注", "企业名称", "报表日期", "金额单位",
]


def normalize_name(value) -> str:
    """规范化项目名称：全角转半角、去空白、统一冒号。"""
    if value is None:
        return ""
    text = str(value)
    if text.lower() in ("nan", "none"):
        return ""
    text = unicodedata.normalize("NFKC", text)
    text = re.sub(r"\s+", "", text)
    text = text.replace("：", ":")
    return text.strip()


def strip_prefix(text: str) -> str:
    """剥离 其中/减/加 等前缀与尾部修饰。"""
    out = text
    for _ in range(2):
        out = re.sub(r"^(其中|减|加)[::]?", "", out)
        out = re.sub(r"^[（(](一|二|三|四|五|六|七|八|九|十)[）)]", "", out)
        out = re.sub(r"^[一二三四五六七八九十]、", "", out)
        out = re.sub(r"^[（(]?\d+[）)、.]?", "", out)
    out = re.sub(r"[（(](净额|账面价值|合计)[）)]$", "", out)
    return out


def resolve_item(name: str) -> tuple[str | None, str]:
    """把客户项目名称解析为标准项目。

    返回 (标准项目, 映射方式)，映射方式为 精确/别名/包含/未映射。
    """
    key = normalize_name(name)
    if not key:
        return None, "未映射"

    candidates = [key]
    stripped = strip_prefix(key)
    if stripped and stripped != key:
        candidates.append(stripped)

    for cand in candidates:
        if cand in _STANDARD_INDEX:
            return _STANDARD_INDEX[cand], ("精确" if cand == key else "别名")
        if cand in _ALIAS_INDEX:
            return _ALIAS_INDEX[cand], "别名"

    # 包含匹配
    for cand in candidates:
        if any(word in cand for word in CONFLICT_KEYWORDS):
            continue
        for frag, std in _CONTAINS_CANDIDATES:
            if frag in cand:
                return std, "包含"
    return None, "未映射"


def is_skip_row(name: str) -> bool:
    key = normalize_name(name)
    if not key:
        return True
    return any(normalize_name(p) in key for p in SKIP_ROW_PATTERNS)


# ------------------------------------------------------------ 索引构建

_ALIAS_INDEX: dict[str, str] = {}
_STANDARD_INDEX: dict[str, str] = {}
_CONTAINS_CANDIDATES: list[tuple[str, str]] = []


def _build_indexes() -> None:
    _ALIAS_INDEX.clear()
    _STANDARD_INDEX.clear()
    _CONTAINS_CANDIDATES.clear()
    for _std, _alts in ALIASES.items():
        for _a in _alts:
            _ALIAS_INDEX[normalize_name(_a)] = _std
    for _stmt, _items in STANDARD_ITEMS.items():
        for _it in _items:
            _STANDARD_INDEX.setdefault(normalize_name(_it), _it)
    for _key, _std in list(_STANDARD_INDEX.items()) + list(_ALIAS_INDEX.items()):
        if len(_key) >= 5:
            _CONTAINS_CANDIDATES.append((_key, _std))
    _CONTAINS_CANDIDATES.sort(key=lambda x: -len(x[0]))


_build_indexes()
